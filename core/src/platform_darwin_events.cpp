int fs_events_replay(const char *root, uint64_t since, uint64_t dev, int64_t since_time,
                     const char *sentinel_dir, PathBag &out) {
    if (!root || !*root || since == 0) return FS_EV_UNSUPPORTED;
    if (int rc = cursor_usable(dev, since, since_time)) return rc;

    Replay r;
    r.bag = &out;
    r.root = root;
    r.rootlen = strlen(root);
    String alt;
    static const char kPrivate[] = "/private";
    const size_t kPrivateLen = sizeof kPrivate - 1;
    if (!strncmp(root, kPrivate, kPrivateLen) && root[kPrivateLen] == '/') {
        alt.assign(root + kPrivateLen);
    } else {
        alt.assign(kPrivate);
        alt.append(root);
    }
    r.alt = alt.c_str();
    r.altlen = alt.size();

    // The watermark. It has to exist before the stream does, so that it is either already in
    // the history or arrives right behind it.
    String sentinel_path, sentinel_leaf;
    if (sentinel_dir && *sentinel_dir) {
        char leaf[64];
        ::snprintf(leaf, sizeof leaf, "/.wfs-diff-%d", (int)::getpid());
        sentinel_leaf.assign(leaf);
        sentinel_path.assign(sentinel_dir);
        sentinel_path.append(leaf);
        ::unlink(sentinel_path.c_str());
        int fd = ::open(sentinel_path.c_str(), O_WRONLY | O_CREAT | O_TRUNC | O_CLOEXEC, 0600);
        if (fd >= 0) {
            ssize_t w = ::write(fd, "w", 1);
            (void)w;
            ::close(fd);
            r.sentinel = sentinel_leaf.c_str();
            r.sentinel_len = sentinel_leaf.size();
        } else {
            sentinel_path.assign("");
        }
    }

    CFStringRef cfp = CFStringCreateWithCString(nullptr, root, kCFStringEncodingUTF8);
    if (!cfp) return FS_EV_UNSUPPORTED;
    CFStringRef cfs = r.sentinel ? CFStringCreateWithCString(nullptr, sentinel_dir, kCFStringEncodingUTF8)
                                 : nullptr;
    const void *roots[2] = {cfp, cfs};
    CFArrayRef watched = CFArrayCreate(nullptr, roots, cfs ? 2 : 1, &kCFTypeArrayCallBacks);
    FSEventStreamContext ctx;
    memset(&ctx, 0, sizeof ctx);
    ctx.info = &r;
    FSEventStreamRef stream =
        FSEventStreamCreate(nullptr, on_events, &ctx, watched, (FSEventStreamEventId)since, 0.0,
                            kFSEventStreamCreateFlagFileEvents | kFSEventStreamCreateFlagNoDefer);
    if (!stream) {
        CFRelease(watched);
        CFRelease(cfp);
        if (cfs) CFRelease(cfs);
        if (sentinel_path.size()) ::unlink(sentinel_path.c_str());
        return FS_EV_UNSUPPORTED;
    }
    // A serial queue is a thread of its own: the callback above runs there and nothing else
    // ever does, so the consumer cannot be the reason an event is dropped.
    r.sem = dispatch_semaphore_create(0);
    dispatch_queue_t q = dispatch_queue_create("world.forks.fs.diff.replay", DISPATCH_QUEUE_SERIAL);
    FSEventStreamSetDispatchQueue(stream, q);
    int rc = FS_EV_OK;
    if (!FSEventStreamStart(stream)) {
        rc = FS_EV_UNSUPPORTED;
    } else {
        // Phase 1, the history. §6.2 measured 21 ms to replay 800 changes over a 50k tree; five
        // seconds is four orders of magnitude of headroom and still bounds the one case that
        // otherwise hangs forever (a cursor the journal cannot serve delivers nothing at all
        // and never sends HistoryDone).
        int64_t deadline = mono_us() + kHistoryUs;
        for (;;) {
            if (__atomic_load_n(&r.done, __ATOMIC_ACQUIRE)) break;
            if (__atomic_load_n(&r.status, __ATOMIC_ACQUIRE) != FS_EV_OK) break;
            int64_t left = deadline - mono_us();
            if (left <= 0) { rc = FS_EV_TIMEOUT; break; }
            dispatch_semaphore_wait(r.sem, dispatch_time(DISPATCH_TIME_NOW, left * 1000));
        }
        // Phase 2a, the watermark: wait for the sentinel to come back round.
        int64_t hard = mono_us() + kTailUs;
        if (rc == FS_EV_OK && r.sentinel && __atomic_load_n(&r.status, __ATOMIC_ACQUIRE) == FS_EV_OK) {
            while (!__atomic_load_n(&r.saw_sentinel, __ATOMIC_ACQUIRE)) {
                int64_t left = hard - mono_us();
                if (left <= 0) { rc = FS_EV_TIMEOUT; break; } // cannot say the replay is alive
                dispatch_semaphore_wait(r.sem, dispatch_time(DISPATCH_TIME_NOW, left * 1000));
            }
        }
        // Phase 2b, the stand-in when there is no sentinel: stop once the stream has been quiet.
        if (rc == FS_EV_OK && !r.sentinel && __atomic_load_n(&r.status, __ATOMIC_ACQUIRE) == FS_EV_OK) {
            for (;;) {
                int64_t left = hard - mono_us();
                if (left <= 0) break;
                if (left > kQuietUs) left = kQuietUs;
                if (dispatch_semaphore_wait(r.sem, dispatch_time(DISPATCH_TIME_NOW, left * 1000)) != 0)
                    break; // quiet: nothing more is arriving for this world
            }
        }
        FSEventStreamStop(stream);
    }
    FSEventStreamInvalidate(stream);
    FSEventStreamRelease(stream);
    dispatch_release(q);
    dispatch_release(r.sem);
    CFRelease(watched);
    CFRelease(cfp);
    if (cfs) CFRelease(cfs);
    if (sentinel_path.size()) ::unlink(sentinel_path.c_str());
    if (rc == FS_EV_OK && r.status != FS_EV_OK) rc = r.status;
    if (rc == FS_EV_OK && !r.done) rc = FS_EV_TIMEOUT;
    return rc;
}

