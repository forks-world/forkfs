// FSEvents: the O(changes) candidate source for `world fs diff` (T1.3).
//
// Measured on 27.0 (docs/CLONE_MODEL_MACOS27.md §6.2): a replay from the fork cursor over a
// 50k-file World with 800 changes delivers 799 unique file-level paths in 21 ms, with
// MustScanSubDirs, UserDropped and KernelDropped all zero. Events are only dropped when the
// consumer is blocked, so the stream here gets a thread of its own and its callback does
// nothing but copy path bytes into a buffer; all verification happens after the join.
//
// Flags (measured in this file's own probe before it was written, see the report in
// docs/TASKS.md T1.3):
//   kFSEventStreamCreateFlagFileEvents  per-file paths instead of per-directory ones. Without
//       it a change is reported as "something under this directory changed" and every diff
//       degenerates into a directory scan.
//   kFSEventStreamCreateFlagNoDefer     deliver the first batch immediately rather than after
//       the latency window. With latency 0 it changes little, but it is what §6.2 measured.
//   NOT kFSEventStreamCreateFlagIgnoreSelf. It suppresses events generated by the process that
//       owns the stream, which for a historical replay is meaningless (the events were recorded
//       long before this stream existed, by some other process). It also would not help: the
//       only writes the fork itself does happen under its temporary clone, a path that is not
//       under the watched root, and were measured not to appear. And under P10 an extra
//       candidate costs one lstat and can never produce a wrong answer, while a wrongly
//       suppressed one would be a missed change.
//   NOT kFSEventStreamCreateFlagWatchRoot. That follows a watched root that is moved while the
//       stream is live; this stream lives for a few milliseconds and replays the past.
//   NOT kFSEventStreamCreateFlagUseCFTypes. char** paths mean no CFString allocation per event.
